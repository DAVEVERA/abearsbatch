export type Dictionary = Dict;
/** Subset die client-componenten van de smakengrid nodig hebben. */
export type CardDict = Pick<Dict, 'grid' | 'characters' | 'volume' | 'pricePlaceholder'>;
export function cardDict(t: Dict): CardDict {
  return { grid: t.grid, characters: t.characters, volume: t.volume, pricePlaceholder: t.pricePlaceholder };
}
